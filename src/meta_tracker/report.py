"""Write a monthly "what changed and why" report in Markdown."""

from __future__ import annotations

import sqlite3
from pathlib import Path

import pandas as pd

from . import analysis, config, db, queries


def _fmt_change(x: float) -> str:
    return f"{x:+.2f} pts"


def _md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(
            f"{v:.2f}" if isinstance(v, float) else str(v) for v in row
        ) + " |")
    return "\n".join(lines)


def monthly_report(conn: sqlite3.Connection, fmt: str, month: str) -> str:
    prev = analysis.previous_month(conn, fmt, month)
    top = queries.run(conn, "top_usage", fmt, month=month, limit=10)
    total, cutoff = conn.execute(
        "SELECT total_battles, cutoff FROM format_months WHERE format=? AND month=?", (fmt, month)
    ).fetchone()

    out = [f"# {fmt} meta report: {month}", ""]
    out += [f"**{total:,} battles** analysed (rating cutoff {cutoff}).", ""]

    month_events = analysis.events(conn, fmt)
    nearby = month_events[(month_events["month"] <= month) & (month_events["month"] >= (prev or month))]
    if not nearby.empty:
        out += ["## Context", ""]
        for e in nearby.itertuples():
            out.append(f"- **{e.month}**: {e.name} ({e.kind}). {e.notes or ''}".rstrip())
        out.append("")

    out += ["## Top 10", "", _md_table(top), ""]

    if prev:
        risers, fallers = analysis.risers_fallers(conn, fmt, month, prev, n=5)
        out += [f"## What changed since {prev}", ""]
        r0, f0 = risers.iloc[0], fallers.iloc[0]
        out.append(
            f"The biggest riser was **{r0.pokemon}** ({r0.before:.1f}% → {r0.after:.1f}%, "
            f"{_fmt_change(r0.change)}). The biggest faller was **{f0.pokemon}** "
            f"({f0.before:.1f}% → {f0.after:.1f}%, {_fmt_change(f0.change)})."
        )
        out.append("")
        out += ["### Risers", "", _md_table(risers), "", "### Fallers", "", _md_table(fallers), ""]

        new = queries.run(conn, "new_to_top_30", fmt, month=month)
        if not new.empty:
            names = ", ".join(f"{r.name} (#{r.rank})" for r in new.itertuples())
            out += ["### New to the top 30", "", names, ""]

        # Explain risers through their partners: a riser whose top teammates also rose
        # suggests a whole archetype gained popularity, not a single Pokémon.
        mates = queries.run(conn, "top_teammates", fmt, month=month, pokemon=r0.pokemon, limit=5)
        if not mates.empty:
            out += [f"### Why might {r0.pokemon} be rising?", ""]
            rising = set(risers["pokemon"])
            for m in mates.itertuples():
                tag = " (also rising)" if m.teammate in rising else ""
                out.append(f"- Paired with **{m.teammate}** on {m.pct_of_teams:.0f}% of teams{tag}")
            out.append("")
    else:
        out += ["_This is the first month in the database, so there is nothing to compare against._", ""]

    edges = analysis.teammate_edges(conn, fmt, month)
    clusters = analysis.archetypes(edges)
    if clusters:
        out += ["## Archetypes (teammate clusters)", ""]
        for i, c in enumerate(clusters, 1):
            out.append(f"{i}. " + ", ".join(sorted(c)))
        out.append("")

    out.append("_Generated by meta-tracker from Smogon usage statistics._")
    return "\n".join(out)


def write_report(conn: sqlite3.Connection, fmt: str, month: str | None = None) -> Path:
    month = month or db.loaded_months(conn, fmt)[-1]
    path = config.REPORTS_DIR / f"{fmt}-{month}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(monthly_report(conn, fmt, month), encoding="utf-8")
    return path
